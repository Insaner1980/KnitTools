internal fun counterDetail(type: ProjectCounterType): UsageDetail =
    when (type) {
        ProjectCounterType.COUNT_UP -> UsageDetail.COUNTER_COUNT_UP
        ProjectCounterType.REPEATING -> UsageDetail.COUNTER_REPEATING
        ProjectCounterType.SHAPING -> UsageDetail.COUNTER_SHAPING
        ProjectCounterType.REPEAT_SECTION -> UsageDetail.COUNTER_REPEAT_SECTION
    }
